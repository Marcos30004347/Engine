bool buildCityLattice(const Polygon &region,
                      const CityLatticeSettings &settings,
                      PolyMesh &out,
                      std::vector<uint32_t> &hexOfFace,
                      CityLatticeReport &report,
                      std::string *error)
{
  out = {};
  hexOfFace.clear();
  report = {};

  const auto fail = [&](const std::string &why) {
    if (error)
    {
      *error = why;
    }

    return false;
  };

  if (region.outer.size() < 3)
  {
    return fail("the city region has no outer ring");
  }

  if (settings.targetCellEdgeMetres <= 0 || settings.hexRadiusTriangles == 0)
  {
    return fail("the lattice settings are degenerate");
  }

  const double t = settings.targetCellEdgeMetres / kQuadEdgePerTriangleEdge;
  const int64_t n = int64_t(settings.hexRadiusTriangles);

  report.triangleEdgeMetres = t;

  const auto position = [&](const int64_t a, const int64_t b) {
    const double x = double(a) * t + double(b) * t * 0.5;
    const double y = double(b) * t * kRowHeight;

    return Point{toUnit(x), toUnit(y)};
  };

  // Which hexagonal patch a point of the lattice belongs to. The patch centres
  // are the sublattice generated by (n, n) and (-n, 2n); inverting that gives
  // i = (2a + b) / 3n and j = (b - a) / 3n, and cube rounding lands on the
  // nearest centre.
  const auto hexOf = [&](const double a, const double b) {
    const double denominator = 3.0 * double(n);

    return cubeRound((2.0 * a + b) / denominator, (b - a) / denominator);
  };

  const geom2::Box box = geom2::bounds(region);

  const double margin = 2.0 * t;
  const double minX = toMetres(box.minX) - margin, maxX = toMetres(box.maxX) + margin;
  const double minY = toMetres(box.minY) - margin, maxY = toMetres(box.maxY) + margin;

  const int64_t bLow = int64_t(std::floor(minY / (t * kRowHeight))) - 1;
  const int64_t bHigh = int64_t(std::ceil(maxY / (t * kRowHeight))) + 1;

  if (bHigh - bLow > 100000)
  {
    return fail("the city region is too large for the lattice spacing");
  }

  // Pass one: which patches hold any ground the city actually wants. A patch is
  // live when one of its triangles has its centroid inside the region; the
  // whole patch is then emitted, so the lattice reaches a little beyond the
  // outline and the trimming afterwards has something to trim.
  std::map<Axial, uint32_t> liveHex;
  std::vector<Tri> triangles;

  const auto centroidOf = [&](const Tri &tri) {
    const double a = double(tri.a) + (tri.down ? 2.0 / 3.0 : 1.0 / 3.0);
    const double b = double(tri.b) + (tri.down ? 2.0 / 3.0 : 1.0 / 3.0);

    return std::pair<double, double>{a, b};
  };

  for (int64_t b = bLow; b <= bHigh; ++b)
  {
    const double rowY = double(b) * t * kRowHeight;
    const double shift = double(b) * t * 0.5;
    const int64_t aLow = int64_t(std::floor((minX - shift) / t)) - 1;
    const int64_t aHigh = int64_t(std::ceil((maxX - shift) / t)) + 1;

    if (rowY < minY - t || rowY > maxY + t)
    {
      continue;
    }

    for (int64_t a = aLow; a <= aHigh; ++a)
    {
      for (const bool down : {false, true})
      {
        const Tri tri{a, b, down};
        const auto centre = centroidOf(tri);

        const double cx = centre.first * t + centre.second * t * 0.5;
        const double cy = centre.second * t * kRowHeight;

        if (!geom2::contains(region, Point{toUnit(cx), toUnit(cy)}))
        {
          continue;
        }

        liveHex.emplace(hexOf(centre.first, centre.second), 0u);
      }
    }
  }

  if (liveHex.empty())
  {
    return fail("no lattice triangle falls inside the city region");
  }

  if (liveHex.size() > settings.maximumHexes)
  {
    return fail("the city region needs " + std::to_string(liveHex.size()) + " hexagonal patches, over the budget of " + std::to_string(settings.maximumHexes));
  }

  {
    uint32_t index = 0;

    for (auto &entry : liveHex)
    {
      entry.second = index++;
    }
  }

  report.hexes = uint32_t(liveHex.size());

  // Pass two: every triangle of every live patch.
  for (int64_t b = bLow; b <= bHigh; ++b)
  {
    const double rowY = double(b) * t * kRowHeight;

    if (rowY < minY - 2 * n * t || rowY > maxY + 2 * n * t)
    {
      continue;
    }

    const double shift = double(b) * t * 0.5;
    const int64_t aLow = int64_t(std::floor((minX - shift) / t)) - 2 * n;
    const int64_t aHigh = int64_t(std::ceil((maxX - shift) / t)) + 2 * n;

    for (int64_t a = aLow; a <= aHigh; ++a)
    {
      for (const bool down : {false, true})
      {
        const Tri tri{a, b, down};
        const auto centre = centroidOf(tri);

        if (liveHex.find(hexOf(centre.first, centre.second)) == liveHex.end())
        {
          continue;
        }

        triangles.push_back(tri);
      }
    }
  }

  std::sort(triangles.begin(), triangles.end());
  triangles.erase(std::unique(triangles.begin(), triangles.end(), [](const Tri &x, const Tri &y) { return !(x < y) && !(y < x); }), triangles.end());

  report.triangles = uint32_t(triangles.size());

  if (triangles.size() > settings.maximumFaces)
  {
    return fail("the lattice would hold " + std::to_string(triangles.size()) + " triangles, over the face budget");
  }

  std::map<Tri, uint32_t> indexOf;

  for (uint32_t i = 0; i < triangles.size(); ++i)
  {
    indexOf.emplace(triangles[i], i);
  }

  // An up triangle's three neighbours. The graph is bipartite - up against down
  // - and three-regular away from the boundary, so a matching leaves very
  // little behind.
  const auto neighboursOfUp = [&](const Tri &tri) {
    return std::array<Tri, 3>{Tri{tri.a, tri.b, true}, Tri{tri.a, tri.b - 1, true}, Tri{tri.a - 1, tri.b, true}};
  };

  std::vector<uint32_t> partner(triangles.size(), geom2::kNoFace);

  // Greedy first, in an order drawn from the triangles' own coordinates rather
  // than from the sweep: the greedy pass is what gives the grid its character,
  // and augmenting afterwards only rescues what it left over.
  struct Candidate
  {
    uint64_t key = 0;
    uint32_t up = 0, down = 0;
  };

  std::vector<Candidate> candidates;

  for (uint32_t i = 0; i < triangles.size(); ++i)
  {
    if (triangles[i].down)
    {
      continue;
    }

    for (const Tri &other : neighboursOfUp(triangles[i]))
    {
      const auto found = indexOf.find(other);

      if (found == indexOf.end())
      {
        continue;
      }

      candidates.push_back({purposeHash(settings.seed, settings.site, 1, triangles[i].a, triangles[i].b, uint64_t(other.a) * 31 + uint64_t(other.b)), i, found->second});
    }
  }

  std::sort(candidates.begin(), candidates.end(), [](const Candidate &x, const Candidate &y) {
    return x.key != y.key ? x.key < y.key : (x.up != y.up ? x.up < y.up : x.down < y.down);
  });

  for (const Candidate &candidate : candidates)
  {
    if (partner[candidate.up] == geom2::kNoFace && partner[candidate.down] == geom2::kNoFace)
    {
      partner[candidate.up] = candidate.down;
      partner[candidate.down] = candidate.up;
    }
  }

  if (settings.maximiseMatching)
  {
    // Kuhn's augmenting paths from the up side, over the hash-ordered adjacency
    // the greedy pass already fixed, so the improvement is deterministic too.
    std::vector<std::vector<uint32_t>> adjacency(triangles.size());

    for (const Candidate &candidate : candidates)
    {
      adjacency[candidate.up].push_back(candidate.down);
    }

    std::vector<uint32_t> stamp(triangles.size(), 0);
    uint32_t visit = 0;

    const auto augment = [&](auto &&self, const uint32_t up) -> bool {
      for (const uint32_t down : adjacency[up])
      {
        if (stamp[down] == visit)
        {
          continue;
        }

        stamp[down] = visit;

        if (partner[down] == geom2::kNoFace || self(self, partner[down]))
        {
          partner[down] = up;
          partner[up] = down;

          return true;
        }
      }

      return false;
    };

    for (uint32_t i = 0; i < triangles.size(); ++i)
    {
      if (triangles[i].down || partner[i] != geom2::kNoFace)
      {
        continue;
      }

      ++visit;
      augment(augment, i);
    }
  }

  // Emit rhombi and leftovers as polygons.
  std::map<Axial, uint32_t> vertexIndex;

  const auto vertexOf = [&](const Axial &v) {
    const auto found = vertexIndex.find(v);

    if (found != vertexIndex.end())
    {
      return found->second;
    }

    const uint32_t index = uint32_t(out.vertices.size());
    out.vertices.push_back(position(v.a, v.b));
    vertexIndex.emplace(v, index);

    return index;
  };

  const auto cornersOf = [](const Tri &tri) {
    if (tri.down)
    {
      return std::array<Axial, 3>{Axial{tri.a + 1, tri.b}, Axial{tri.a + 1, tri.b + 1}, Axial{tri.a, tri.b + 1}};
    }

    return std::array<Axial, 3>{Axial{tri.a, tri.b}, Axial{tri.a + 1, tri.b}, Axial{tri.a, tri.b + 1}};
  };

  std::vector<bool> emitted(triangles.size(), false);

  for (uint32_t i = 0; i < triangles.size(); ++i)
  {
    if (emitted[i])
    {
      continue;
    }

    const Tri &tri = triangles[i];
    const auto centre = centroidOf(tri);
    const uint32_t hex = liveHex.find(hexOf(centre.first, centre.second))->second;
    const uint32_t mate = partner[i];

    if (mate == geom2::kNoFace)
    {
      const auto corners = cornersOf(tri);
      out.faces.push_back({vertexOf(corners[0]), vertexOf(corners[1]), vertexOf(corners[2])});
      hexOfFace.push_back(hex);
      emitted[i] = true;
      ++report.unpaired;

      continue;
    }

    if (tri.down)
    {
      continue; // The up triangle of the pair emits it.
    }

    // The merged quad, built from the shared edge rather than from the three
    // cases: corners [a_i, apex of the mate, a_i+1, a_i+2], where the shared
    // edge is (a_i, a_i+1). One construction, and it stays counter-clockwise
    // because both triangles are.
    const auto mine = cornersOf(tri);
    const auto theirs = cornersOf(triangles[mate]);

    uint32_t shared = 4;

    for (uint32_t k = 0; k < 3; ++k)
    {
      const Axial &p = mine[k];
      const Axial &q = mine[(k + 1) % 3];
      bool hasP = false, hasQ = false;

      for (const Axial &r : theirs)
      {
        hasP = hasP || r == p;
        hasQ = hasQ || r == q;
      }

      if (hasP && hasQ)
      {
        shared = k;

        break;
      }
    }

    if (shared == 4)
    {
      return fail("a matched pair of triangles does not share an edge");
    }

    Axial apex{};

    for (const Axial &r : theirs)
    {
      if (!(r == mine[shared]) && !(r == mine[(shared + 1) % 3]))
      {
        apex = r;
      }
    }

    out.faces.push_back({vertexOf(mine[shared]), vertexOf(apex), vertexOf(mine[(shared + 1) % 3]), vertexOf(mine[(shared + 2) % 3])});
    hexOfFace.push_back(hex);

    emitted[i] = true;
    emitted[mate] = true;
    ++report.pairs;
  }

  return true;
}

