using geom2::toMetres;
using geom2::toUnit;

// sqrt(3)/2, as a literal rather than as a call: it is the one irrational the
// lattice needs, and a named constant is identical on every target where a
// std::sqrt at start-up is only nearly so.
constexpr double kRowHeight = 0.86602540378443864676;

uint64_t splitmix64(uint64_t value)
{
  value += 0x9e3779b97f4a7c15ull;
  value = (value ^ (value >> 30)) * 0xbf58476d1ce4e5b9ull;
  value = (value ^ (value >> 27)) * 0x94d049bb133111ebull;

  return value ^ (value >> 31);
}

// Purpose-addressed randomness: the seed, the site, what is being decided and
// the stable identity of the thing it is decided for. Never the traversal
// order, so permuting the work list cannot change the result.
uint64_t purposeHash(const uint64_t seed, const uint64_t site, const uint64_t purpose, const int64_t a, const int64_t b, const uint64_t extra = 0)
{
  uint64_t h = splitmix64(seed ^ 0x6a09e667f3bcc908ull);
  h = splitmix64(h ^ site);
  h = splitmix64(h ^ purpose);
  h = splitmix64(h ^ uint64_t(a) * 0x9e3779b97f4a7c15ull);
  h = splitmix64(h ^ uint64_t(b) * 0xc2b2ae3d27d4eb4full);

  return splitmix64(h ^ extra);
}

// A lattice vertex, in axial coordinates over the basis e1 = (t, 0) and
// e2 = (t/2, t sqrt3/2).
struct Axial
{
  int64_t a = 0, b = 0;

  bool operator<(const Axial &other) const
  {
    return a != other.a ? a < other.a : b < other.b;
  }

  bool operator==(const Axial &other) const
  {
    return a == other.a && b == other.b;
  }
};

// A triangle of the lattice: the cell it belongs to, and which of the cell's
// two triangles it is. Up is [(a,b), (a+1,b), (a,b+1)] and down is
// [(a+1,b), (a+1,b+1), (a,b+1)]; both are counter-clockwise.
struct Tri
{
  int64_t a = 0, b = 0;
  bool down = false;

  bool operator<(const Tri &other) const
  {
    if (a != other.a)
    {
      return a < other.a;
    }

    if (b != other.b)
    {
      return b < other.b;
    }

    return int(down) < int(other.down);
  }
};

// Cube rounding on a hexagonal lattice: the nearest lattice point to a
// fractional axial coordinate. The Voronoi cell of a hex lattice point is a
// regular hexagon, so rounding in cube coordinates and repairing the largest
// error is exactly the nearest-point rule.
Axial cubeRound(const double i, const double j)
{
  const double x = i;
  const double z = j;
  const double y = -x - z;

  double rx = std::round(x), ry = std::round(y), rz = std::round(z);

  const double dx = std::abs(rx - x), dy = std::abs(ry - y), dz = std::abs(rz - z);

  if (dx > dy && dx > dz)
  {
    rx = -ry - rz;
  }
  else if (dy > dz)
  {
    ry = -rx - rz;
  }
  else
  {
    rz = -rx - ry;
  }

  (void)ry;

  return {int64_t(rx), int64_t(rz)};
}

