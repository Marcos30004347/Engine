#pragma once

#include "procedural/geom2/QuadMesh.hpp"

namespace procedural::world::citywfc {

using geom2::Point;
using geom2::Polygon;
using geom2::PolyMesh;

// The unrelaxed grid: a triangular lattice, cut into hexagonal patches, with
// pairs of triangles merged into rhombi and everything then subdivided into
// quads. Townscaper's construction, with one change that a bounded city allows.
//
// Sylves builds this infinitely, so it pairs triangles inside one hexagon,
// relaxes a cluster of hexagons and keeps only the middle. A city is bounded and
// known before generation starts, and that buys the simplification this file is
// written around: hexagonal patches of side `n` triangles are a SUBLATTICE
// PARTITION of one global triangular lattice - their centres are the lattice
// points generated by (n, n) and (-n, 2n) in axial coordinates - so there are no
// per-patch meshes to translate and weld, the pairing may cross a patch
// boundary, and the seam rows of small triangles a per-patch pairing leaves
// behind never exist.
//
// The patches are kept anyway, for what they are actually good for here: the
// coverage unit that decides which part of the lattice exists, provenance for
// the seam test, and a chunk identity for streaming later.

struct CityLatticeSettings
{
  // The edge a finished quad should have. The triangle lattice is derived from
  // it, never authored: merging two triangles and subdividing gives four quads
  // of edge about 0.466 t, so t is this divided by that.
  double targetCellEdgeMetres = 6;

  // Hexagonal patch side, in triangles. A patch holds 6 n^2 triangles and about
  // 2 n^2 finished cells.
  uint32_t hexRadiusTriangles = 5;

  uint64_t seed = 1;
  uint64_t site = 0; // So two settlements never share a lattice phase.

  uint32_t maximumHexes = 512;
  uint32_t maximumFaces = 65536;

  // Pairing leftovers become three quads rather than four and so come out
  // smaller. Reported, and gated by the caller.
  bool maximiseMatching = true;
};

struct CityLatticeReport
{
  uint32_t hexes = 0;
  uint32_t triangles = 0;
  uint32_t pairs = 0;
  uint32_t unpaired = 0;
  double triangleEdgeMetres = 0;
};

// The lattice, as polygons, before any subdivision: rhombi and leftover
// triangles. `hexOfFace` names the patch each came from.
bool buildCityLattice(const Polygon &region,
                      const CityLatticeSettings &settings,
                      PolyMesh &out,
                      std::vector<uint32_t> &hexOfFace,
                      CityLatticeReport &report,
                      std::string *error = nullptr);

// The ratio between a finished quad's edge and the triangle edge it came from.
// Two triangles of side t merge into a rhombus of area (sqrt 3 / 2) t^2, which
// ortho-subdivides into four quads of that quarter.
inline constexpr double kQuadEdgePerTriangleEdge = 0.4655;

} // namespace procedural::world::citywfc
