// Run with Playwright available in NODE_PATH. This tests the served native city.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
(async () => {
  const url = process.argv[2] || 'http://127.0.0.1:8765';
  const output = process.argv[3] || 'build/city-viewer-checks';
  await fs.mkdir(output, { recursive: true });
  const options = { headless: true };
  if (process.env.BROWSER_EXECUTABLE) options.executablePath = process.env.BROWSER_EXECUTABLE;
  if (process.platform === 'darwin') options.args = ['--enable-webgl', '--use-angle=metal'];
  const browser = await chromium.launch(options);
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', e => errors.push(String(e)));
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
    await page.goto(url);
    await page.waitForFunction(() => window.cityViewer?.ready || window.cityViewer?.error, {}, { timeout: 180000 });
    const snapshot = () => page.evaluate(() => window.cityViewer);
    assert.equal((await snapshot()).ready, true);
    await page.waitForTimeout(2500);
    const overview = await snapshot();
    assert.equal(overview.glError, 0);
    assert(overview.loadedTriangles > 0 && overview.buildings > 0);
    await page.screenshot({ path: path.join(output, 'overview.png') });
    await page.locator('#street').click();
    await page.waitForTimeout(1800);
    const street = await snapshot();
    await page.screenshot({ path: path.join(output, 'street.png') });
    await page.locator('#view').focus();
    const before = (await snapshot()).position;
    await page.keyboard.down('KeyW'); await page.waitForTimeout(700); await page.keyboard.up('KeyW');
    const after = (await snapshot()).position;
    assert(Math.hypot(...after.map((p, i) => p-before[i])) > 1, 'W moves the camera');
    const landmarkKind=process.argv[4] || 'keep';
    const keep = await page.locator('#landmark option').evaluateAll((options,kind) => options.find(o => o.textContent.startsWith(kind+' '))?.value,landmarkKind);
    assert(keep !== undefined, 'Native scene includes the requested landmark');
    await page.locator('#landmark').selectOption(keep);
    await page.locator('#visit').click(); await page.waitForTimeout(700);
    await page.screenshot({ path: path.join(output, 'castle.png') });
    assert.equal(await page.locator('#interior').isDisabled(), false);
    await page.locator('#interior').click(); await page.waitForTimeout(700);
    const interior = await snapshot();
    assert(interior.position.every(Number.isFinite));
    await page.screenshot({ path: path.join(output, 'interior.png') });
    await page.locator('#nextRoom').click(); await page.waitForTimeout(300);
    assert.notDeepEqual((await snapshot()).position, interior.position, 'Next room changes the viewpoint');
    await page.locator('#overview').click(); await page.waitForTimeout(300);
    await page.locator('summary').filter({hasText:'View options & origin'}).click();
    const roofed = (await snapshot()).visibleTriangles;
    await page.locator('#roofs').uncheck(); await page.waitForTimeout(300);
    assert((await snapshot()).visibleTriangles < roofed, 'Roof inspection hides native roof triangles');
    await page.locator('#cutaway').check(); await page.waitForTimeout(300);
    await page.screenshot({ path: path.join(output, 'cutaway.png') });
    assert.equal((await snapshot()).glError, 0);
    assert.deepEqual(errors, []);
    const result = { overview, street, interior, movementMetres: Math.hypot(...after.map((p, i) => p-before[i])), errors };
    await fs.writeFile(path.join(output, 'browser-validation.json'), JSON.stringify(result, null, 2));
    console.log(JSON.stringify(result, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
