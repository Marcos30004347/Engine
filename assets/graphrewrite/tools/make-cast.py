#!/usr/bin/env python3
"""Generate a .graphfacts cast for story.graphwrite.

    make-cast.py --people 200 --seed 7 > big.graphfacts

Villages of roughly twenty-five, three houses each with a head, his wife and
their children, plus a few singles and widows; birth years so that some come
of age during the run; peace between every pair of houses in a village; a
handful of likings to start things off. Every line matches an edge type the
story declares, and the loader rejects anything that does not.
"""
import argparse
import random

MALE_A = ["Aeth", "Aelf", "Ald", "Beorn", "Bert", "Ceol", "Cen", "Cuth", "Cyne", "Dun", "Ead", "Ealh", "Eor", "Frid", "God",
          "Here", "Hild", "Leof", "Os", "Sig", "Wig", "Wulf", "Wil", "Ord", "Ecg", "Aesc", "Ban", "Brand", "Grim", "Hun"]
MALE_B = ["ric", "wald", "helm", "wine", "stan", "mund", "red", "gar", "noth", "laf", "wulf", "heard", "frith", "bald", "here"]
FEMALE_A = ["Aeth", "Aelf", "Ald", "Bert", "Cuth", "Cyne", "Ead", "Eal", "Frid", "God", "Hild", "Leof", "Os", "Sae", "Wig",
            "Wulf", "Wyn", "Ceol", "Eor", "Hun", "Sig", "Aesc", "Beorn", "Ecg", "Here"]
FEMALE_B = ["wyn", "gyth", "burh", "flaed", "swith", "thryth", "run", "hild", "lafa", "gifu", "frith", "wara", "leofu"]
VILLAGES = ["Wealdholt", "Stanmere", "Ashcombe", "Byrnham", "Coldwell", "Dunford", "Elmhurst", "Fenwick", "Grimsby",
            "Hartley", "Ingleton", "Kirkstead", "Lindhurst", "Marston", "Norbury", "Oakham", "Pendle", "Rydal", "Selby",
            "Thornby", "Upton", "Wendover", "Yarrow"]
HOUSE_B = ["ing", "ring", "ling", "sing", "ming"]
REALM_A = ["Wess", "Mer", "North", "East", "South", "West", "Deir", "Bern", "Kent", "Lind", "Hwicc", "Mag",
           "Elm", "Sur", "Suss", "Cant", "Rheg", "Gwyn", "Powy", "Dyf", "Strath", "Alb", "Fort", "Dal",
           "Ess", "Midd", "Hast", "Wight", "Peak", "Chilt", "Wreo", "Tom", "Pec", "Gyrw", "Hers", "Nox"]
REALM_B = ["sex", "cia", "umbria", "anglia", "mark", "land", "heath", "holm", "gard", "wold"]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--people", type=int, default=200)
    parser.add_argument("--seed", type=int, default=1)
    parser.add_argument("--year", type=int, default=1000, help="the year the story opens")
    parser.add_argument("--village", type=int, default=25, help="people per village, roughly")
    parser.add_argument("--realm", type=int, default=16, help="villages per realm; one king each")
    args = parser.parse_args()

    rng = random.Random(args.seed)

    # A token is one word, because the loader matches a line word by word, and
    # every person in the world needs a distinct one. So a person is written
    # Given_Family__Village: an underscore is a space, and everything from the
    # double underscore is there to keep the token unique and is never read
    # out. Uniqueness then costs nothing - a given name has only to be
    # distinct inside its family, and a family inside its village - which is
    # what replaced numbering people Wulfric2, Wulfric3.
    villages_used = set()

    def unique_village(base):
        if base not in villages_used:
            villages_used.add(base)
            return base
        n = 2
        while base + str(n) in villages_used:
            n += 1
        villages_used.add(base + str(n))
        return base + str(n)

    def draw(pool, taken):
        for _ in range(200):
            n = rng.choice(pool[0]) + rng.choice(pool[1])
            if n not in taken:
                taken.add(n)
                return n
        n = rng.choice(pool[0]) + rng.choice(pool[1])
        k = 2
        while n + str(k) in taken:
            k += 1
        taken.add(n + str(k))
        return n + str(k)

    year = args.year
    lines = ["# Generated by tools/make-cast.py --people %d --seed %d. Year %d opens the story." % (args.people, args.seed, year),
             "#",
             "# A person's token is Given_Family__Village: the story reads it as",
             "# 'Given Family'.",
             ""]
    people = 0
    likes = []
    villages = 0
    # One king over two hundred thousand people is not a kingdom of this
    # period, and it is not a shape the matcher likes either: every sworn
    # house against every claimant is quadratic in houses. A petty kingdom
    # every `--realm` villages keeps the court joins the size of a court.
    realms_used = set()
    realm = None
    crown = None
    sworn = []
    courts = []

    while people < args.people:
        if villages % args.realm == 0:
            if realm is not None:
                courts.append((realm, crown, sworn))
            realm = draw((REALM_A, REALM_B), realms_used)
            crown = None
            sworn = []

        village = unique_village(VILLAGES[villages % len(VILLAGES)])
        villages += 1
        tag = "__" + village
        church = "St" + rng.choice(FEMALE_A) + rng.choice(FEMALE_B) + tag
        lines += ["# --- %s ---" % village, "", "%s is a church in %s" % (church, village), ""]

        # A priest for the parish. He is of no house and takes no wife, so
        # the courtship and match rules pass him by, and he gets no `keeps
        # the peace`, which is what hatching a plot consumes - so he cannot
        # start one. He can still be drawn into somebody else's.
        priest = "Father" + rng.choice(MALE_A) + rng.choice(MALE_B) + tag
        lines += ["%s serves %s" % (priest, church), "%s is man" % priest, "%s is alive" % priest,
                  "%s born in %d" % (priest, year - rng.randint(30, 60)), "%s is grown" % priest,
                  "%s lives in %s" % (priest, village), ""]
        houses = []
        families = set()
        target = min(args.village, args.people - people)
        in_village = 0
        grown_men, grown_women = [], []

        while in_village < target:
            family = draw((MALE_A, HOUSE_B), families)
            house = family + tag
            houses.append(house)
            given = set()
            head = draw((MALE_A, MALE_B), given) + "_" + family + tag
            wife_name = draw((FEMALE_A, FEMALE_B), given) + "_" + family + tag
            head_born = year - rng.randint(36, 58)
            wife_born = head_born + rng.randint(2, 10)
            lines += ["# The house of %s." % family, ""]

            def person(n, female, born, extra):
                nonlocal people, in_village
                people += 1
                in_village += 1
                return ["%s is of house %s" % (n, house), "%s is %s" % (n, "woman" if female else "man"), "%s is alive" % n,
                        "%s born in %d" % (n, born), "%s lives in %s" % (n, village)] + extra

            lines += ["%s is head of %s" % (head, house)]
            lines += person(head, False, head_born, ["%s is grown" % head, "%s keeps the peace" % head])
            widower = rng.random() < 0.15
            if widower:
                lines += ["%s is unmarried" % head, "%s is unattached" % head]
            else:
                lines += person(wife_name, True, wife_born, ["%s is grown" % wife_name, "%s keeps the peace" % wife_name] +
                                (["%s is fertile" % wife_name] if year - wife_born < 45 else []))
                lines += ["%s is husband of %s" % (head, wife_name), "%s is wife of %s" % (wife_name, head)]
            lines.append("")

            # The first house of the world holds the crown.
            if crown is None and not widower:
                crown = (head, wife_name)
            else:
                sworn.append(house)

            for _ in range(rng.randint(2, 5)):
                if in_village >= target:
                    break
                female = rng.random() < 0.5
                child = draw((FEMALE_A, FEMALE_B) if female else (MALE_A, MALE_B), given) + "_" + family + tag
                born = min(wife_born + rng.randint(17, 34), year - 1)
                age = year - born
                extra = ["%s is child of %s" % (child, head), "%s is father of %s" % (head, child)]
                if not widower:
                    extra += ["%s is child of %s" % (child, wife_name), "%s is mother of %s" % (wife_name, child)]
                if age >= 16:
                    extra += ["%s is grown" % child, "%s is unmarried" % child, "%s is unattached" % child,
                              "%s keeps the peace" % child]
                    if female:
                        extra.append("%s is fertile" % child)
                        grown_women.append(child)
                    else:
                        grown_men.append(child)
                else:
                    extra.append("%s is young" % child)
                    if age < 5:
                        extra.append("%s is an infant" % child)
                lines += person(child, female, born, extra)
                lines.append("")

            if in_village < target and rng.random() < 0.6:
                female = rng.random() < 0.5
                n = draw((FEMALE_A, FEMALE_B) if female else (MALE_A, MALE_B), given) + "_" + family + tag
                born = year - rng.randint(18, 50)
                extra = ["%s is grown" % n, "%s is unmarried" % n, "%s is unattached" % n, "%s keeps the peace" % n]
                if female and year - born < 45:
                    extra.append("%s is fertile" % n)
                    grown_women.append(n)
                elif not female:
                    grown_men.append(n)
                lines += person(n, female, born, extra)
                lines.append("")

        for a in houses:
            for b in houses:
                if a != b:
                    lines.append("%s is at peace with %s" % (a, b))
        lines.append("")

        rng.shuffle(grown_men)
        rng.shuffle(grown_women)
        for m, w in list(zip(grown_men, grown_women))[:2]:
            likes.append((m, w))

    unattached = set(m for m, _ in likes)
    lines = [l for l in lines if not (l.endswith(" is unattached") and l.split(" is unattached")[0] in unattached)]

    lines += ["# Likings to start with.", ""]
    for m, w in likes:
        lines += ["%s likes %s" % (m, w), "%s smitten on %d" % (m, year - 1)]

    # The realms. Every house but its own king's swears to him.
    if realm is not None:
        courts.append((realm, crown, sworn))

    lines += ["", "# --- the realms ---", ""]

    for name, king, houses in courts:
        if king is None:
            continue

        lines += ["%s is king of %s" % (king[0], name),
                  "%s is queen of %s" % (king[1], name),
                  "%s wants an heir" % name]
        lines += ["%s swears to %s" % (house, name) for house in houses]
        lines.append("")

    print("\n".join(lines))


if __name__ == "__main__":
    main()
